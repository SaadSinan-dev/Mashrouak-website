export function arrayItem(key: string): unknown {
  if (key === "technologies") return "";
  if (key === "navigation") return { label: bi(), to: "/" };
  if (key === "evidence") return { label: bi(), url: "" };
  if (key === "gallery") return { url: "", alt: bi() };
  if (key === "sections")
    return {
      id: `section-${crypto.randomUUID().slice(0, 8)}`,
      kind: "text",
      visible: true,
      background: "default",
      title: bi(),
      body: bi(),
      image: null,
      buttonLabel: bi(),
      buttonUrl: "",
    };
  return bi();
}
